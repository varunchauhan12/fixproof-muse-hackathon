"""
Evidence contract models for FixProof Milestone 6C.6B.
Defines typed Pydantic v2 schemas for computer-vision match evidence,
temporal correspondence intervals, and bounded Nemotron investigation reports.

Invariants:
- Every finding must reference actual evidence identifiers.
- Rejects references to nonexistent evidence.
- Distinguishes measured metrics from model-generated narrative.
- Does not treat L2 distance or similarity as a probability.
- Never exposes or stores private internal reasoning traces.
"""

from datetime import datetime, timezone
from typing import Any, Dict, List, Literal, Optional, Set, Tuple
import uuid

from pydantic import BaseModel, Field, field_validator, model_validator


RecommendedAction = Literal[
    "ESCALATE_LEGAL_TAKEDOWN",
    "FLAG_FOR_BROKER_LICENSING",
    "DISMISS_FAIR_USE",
    "NEEDS_FULL_VIDEO_REVIEW",
    "MONITOR_ACCOUNT",
]

ConfidenceAssessment = Literal[
    "HIGH_CONFIDENCE_MATCH",
    "MODERATE_PROBABILITY",
    "INCONCLUSIVE_DATA",
    "CONFIRMED_DISTINCT",
]

ContinuityStatus = Literal[
    "CONTINUOUS_MATCH",
    "SPARSE_MATCH",
    "SINGLETON",
]

FindingCategory = Literal[
    "TIMELINE_CORRESPONDENCE",
    "PERCEPTUAL_SIMILARITY",
    "ANOMALY_OR_DISCREPANCY",
    "LIMITATION",
]


class FrameEvidence(BaseModel):
    """
    Structured forensic record of an individual frame comparison.
    Derived strictly from CV extractor, FAISS vector matcher, and pHash analysis.
    """
    evidence_id: str
    suspect_timestamp_sec: float
    suspect_frame_idx: int
    source_asset_id: Optional[str] = None
    source_frame_id: Optional[int] = None
    source_timestamp_sec: Optional[float] = None
    source_filename: Optional[str] = None
    l2_distance: Optional[float] = None
    visual_similarity_score: Optional[float] = None
    phash_distance: Optional[int] = None
    phash_score: Optional[int] = None
    phash_match: Optional[bool] = None
    similarity_status: Literal["CONFIRMED_MATCH", "SUSPECT_MATCH", "NO_MATCH", "UNVERIFIED"] = "UNVERIFIED"
    vision_verification: Optional[Dict[str, Any]] = None
    raw_details: Optional[Dict[str, Any]] = None


class TimelineInterval(BaseModel):
    """
    Temporally coherent interval of matching frames between a suspect video
    and a specific reference source asset.
    """
    interval_id: str
    source_asset_id: str
    suspect_start_sec: float
    suspect_end_sec: float
    source_start_sec: float
    source_end_sec: float
    duration_sec: float
    frame_count: int
    mean_l2_distance: float
    min_l2_distance: float
    phash_match_ratio: float
    continuity_status: ContinuityStatus = "SINGLETON"
    evidence_ids: List[str] = Field(default_factory=list)


class InvestigationInput(BaseModel):
    """
    Validated evidence payload provided to the Nemotron investigation engine.
    Contains strictly measured facts and pre-clustered timeline intervals.
    """
    incident_id: str
    investigation_type: Literal["FULL_VIDEO_SCAN", "URL_SCREENING"]
    platform: Optional[str] = None
    suspect_filename: Optional[str] = None
    duration_seconds: Optional[float] = None
    frames_evidence: List[FrameEvidence] = Field(default_factory=list)
    timeline_intervals: List[TimelineInterval] = Field(default_factory=list)
    overall_cv_status: str
    matched_assets: List[str] = Field(default_factory=list)
    metadata: Dict[str, Any] = Field(default_factory=dict)


class FindingItem(BaseModel):
    """
    Individual evidence-grounded finding.
    Must cite valid evidence identifiers (interval_id or evidence_id) present in the input.
    """
    finding_id: str
    category: FindingCategory
    statement: str
    evidence_ids: List[str] = Field(default_factory=list)
    measured_metrics: Dict[str, Any] = Field(default_factory=dict)

    @field_validator("evidence_ids")
    @classmethod
    def validate_non_empty_evidence(cls, v: List[str]) -> List[str]:
        if not v:
            raise ValueError("Every finding must reference at least one evidence identifier.")
        return v


class InvestigationReport(BaseModel):
    """
    Complete, validated forensic investigation report generated by the Nemotron engine.
    Aligned with the PostgreSQL nemotron_reports database schema.
    """
    report_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    incident_id: str
    model_id: str
    prompt_version: str = "v1.0"
    summary: str
    recommended_action: RecommendedAction
    confidence_assessment: ConfidenceAssessment
    human_review_required: bool = False
    timeline_intervals: List[TimelineInterval] = Field(default_factory=list)
    findings: List[FindingItem] = Field(default_factory=list)
    unresolved_questions: List[str] = Field(default_factory=list)
    contradictions_detected: List[str] = Field(default_factory=list)
    limitations_disclosed: List[str] = Field(default_factory=list)
    evidence_references: List[str] = Field(default_factory=list)
    operational_metadata: Dict[str, Any] = Field(default_factory=dict)


class ReportHistoryItem(BaseModel):
    """
    Compact summary record of a persisted investigation report for history listings.
    """
    report_id: str
    incident_id: str
    created_at: str = ""
    model_id: str = "nvidia/Nemotron-3_5-Lightning"
    recommended_action: RecommendedAction = "NEEDS_FULL_VIDEO_REVIEW"
    confidence_assessment: ConfidenceAssessment = "INCONCLUSIVE_DATA"
    validation_status: str = "VALIDATED"
    human_review_required: bool = False
    summary: str = ""

    @model_validator(mode="before")
    @classmethod
    def extract_from_raw_report(cls, data: Any) -> Any:
        if isinstance(data, dict):
            if "validation_status" not in data or not data["validation_status"]:
                op_meta = data.get("operational_metadata") or {}
                data["validation_status"] = (
                    op_meta.get("validation_status") or "VALIDATED"
                )
            if "created_at" not in data or not data["created_at"]:
                op_meta = data.get("operational_metadata") or {}
                data["created_at"] = str(op_meta.get("created_at") or "")
        return data


def validate_report_evidence_references(
    report: InvestigationReport,
    valid_evidence_ids: Set[str],
) -> Tuple[bool, List[str]]:
    """
    Validates that every evidence reference cited in the report findings
    and evidence_references exists in the valid set.
    
    Returns:
        (is_valid, list_of_invalid_ids)
    """
    invalid_ids = []
    
    for finding in report.findings:
        for eid in finding.evidence_ids:
            if eid not in valid_evidence_ids:
                invalid_ids.append(eid)
                
    for eid in report.evidence_references:
        if eid not in valid_evidence_ids and eid not in invalid_ids:
            invalid_ids.append(eid)
            
    return (len(invalid_ids) == 0, invalid_ids)


def build_frame_evidence_from_matches(frame_matches: List[Dict[str, Any]]) -> List[FrameEvidence]:
    """
    Converts raw frame matches from matcher.py or url_screener.py
    into a typed list of FrameEvidence records.
    """
    evidences: List[FrameEvidence] = []
    
    for idx, item in enumerate(frame_matches):
        sub = item.get("submitted_frame") or {}
        best = item.get("best_match")
        
        frame_idx = sub.get("frame_index", idx)
        ts_sec = float(sub.get("timestamp_sec") or 0.0)
        ev_id = f"frame_{frame_idx}_t{int(ts_sec)}s"
        
        if best:
            src_asset = best.get("source_asset_id")
            src_frame = best.get("source_frame_id")
            src_ts = float(best.get("source_timestamp_sec") or 0.0) if best.get("source_timestamp_sec") is not None else None
            src_fn = best.get("source_filename")
            l2_dist = float(best["l2_distance"]) if best.get("l2_distance") is not None else None
            
            phash_ev = best.get("phash_evidence") or {}
            phash_dist = phash_ev.get("hamming_distance")
            phash_score = best.get("phash_score")
            phash_match = best.get("phash_match")
            
            if best.get("match_confirmed"):
                status = "CONFIRMED_MATCH"
            elif l2_dist is not None and l2_dist < 0.75:
                status = "SUSPECT_MATCH"
            else:
                status = "NO_MATCH"
                
            vis_score = best.get("visual_similarity_score")
            if vis_score is None and best.get("confidence_score") is not None:
                vis_score = float(best["confidence_score"])
            vision_ver = best.get("vision_verification")
                
            evidences.append(
                FrameEvidence(
                    evidence_id=ev_id,
                    suspect_timestamp_sec=ts_sec,
                    suspect_frame_idx=frame_idx,
                    source_asset_id=src_asset,
                    source_frame_id=src_frame,
                    source_timestamp_sec=src_ts,
                    source_filename=src_fn,
                    l2_distance=l2_dist,
                    visual_similarity_score=vis_score,
                    phash_distance=phash_dist,
                    phash_score=phash_score,
                    phash_match=phash_match,
                    similarity_status=status,
                    vision_verification=vision_ver,
                    raw_details={"vector_id": best.get("vector_id")},
                )
            )
        else:
            evidences.append(
                FrameEvidence(
                    evidence_id=ev_id,
                    suspect_timestamp_sec=ts_sec,
                    suspect_frame_idx=frame_idx,
                    similarity_status="NO_MATCH",
                )
            )
            
    return evidences


def build_investigation_input_from_incident(
    incident_data: Dict[str, Any],
    intervals: Optional[List[TimelineInterval]] = None,
) -> InvestigationInput:
    """
    Transforms a raw incident record (from matcher.py or url_screener.py)
    into a typed, validated InvestigationInput.
    """
    incident_id = str(incident_data.get("incident_id") or uuid.uuid4())
    inv_type = incident_data.get("investigation_type", "FULL_VIDEO_SCAN")
    if inv_type not in ("FULL_VIDEO_SCAN", "URL_SCREENING"):
        inv_type = "FULL_VIDEO_SCAN"
        
    raw_matches = incident_data.get("frame_matches") or []
    frames_ev = build_frame_evidence_from_matches(raw_matches)
    
    matched_ids = []
    raw_matched = incident_data.get("matched_assets") or []
    for ma in raw_matched:
        if isinstance(ma, dict):
            aid = ma.get("asset_id")
            if aid:
                matched_ids.append(str(aid))
        elif ma:
            matched_ids.append(str(ma))
            
    return InvestigationInput(
        incident_id=incident_id,
        investigation_type=inv_type,
        platform=incident_data.get("platform"),
        suspect_filename=incident_data.get("suspect_filename"),
        duration_seconds=float(incident_data.get("duration_seconds") or 0.0),
        frames_evidence=frames_ev,
        timeline_intervals=intervals or [],
        overall_cv_status=incident_data.get("overall_status") or "CLEAN",
        matched_assets=matched_ids,
        metadata=incident_data.get("metadata") or {},
    )
